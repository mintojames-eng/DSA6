def run_experiment(n, dataset_type):

    data = create_dataset(n, dataset_type)

    # ------------------------------------------------------------
    # PLAIN BST
    # ------------------------------------------------------------

    bst = PlainBST()

    start = time.perf_counter()

    for key in data:
        bst.insert(key, f"Patient_{key}")

    bst_time = time.perf_counter() - start

    bst_height = bst.height()

    # ------------------------------------------------------------
    # AVL
    # ------------------------------------------------------------

    avl = AVLTree()

    start = time.perf_counter()

    for key in data:
        avl.insert(key, f"Patient_{key}")

    avl_time = time.perf_counter() - start

    avl_height = avl.height()

    rotations = avl.rotations

    # ------------------------------------------------------------
    # SUCCESSFUL SEARCHES
    # ------------------------------------------------------------

    search_count = min(1000, n)

    search_keys = random.sample(
        list(range(1, n + 1)),
        search_count
    )

    # BST searches
    bst.comparisons = 0

    for key in search_keys:
        bst.search(key)

    avg_bst_comparisons = (
        bst.comparisons / search_count
    )

    # AVL searches
    avl.comparisons = 0

    for key in search_keys:
        avl.search(key)

    avg_avl_comparisons = (
        avl.comparisons / search_count
    )

    # ------------------------------------------------------------
    # DELETE RANDOM 20%
    # ------------------------------------------------------------

    delete_count = int(0.20 * n)

    delete_keys = random.sample(
        list(range(1, n + 1)),
        delete_count
    )

    for key in delete_keys:
        bst.delete(key)
        avl.delete(key)

    bst_height_after_delete = bst.height()
    avl_height_after_delete = avl.height()

    # ------------------------------------------------------------
    # VALIDATION
    # ------------------------------------------------------------

    assert bst.is_bst()
    assert avl.is_bst()
    assert avl.is_balanced()

    return {
        "N": n,
        "Dataset": dataset_type,
        "BST Height": bst_height,
        "AVL Height": avl_height,
        "BST Insert Time (s)": bst_time,
        "AVL Insert Time (s)": avl_time,
        "AVL Rotations": rotations,
        "BST Avg Search Comparisons": avg_bst_comparisons,
        "AVL Avg Search Comparisons": avg_avl_comparisons,
        "BST Height After 20% Delete": bst_height_after_delete,
        "AVL Height After 20% Delete": avl_height_after_delete
    }


