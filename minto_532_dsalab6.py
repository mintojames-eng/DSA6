class PlainBST:

    def __init__(self):
        self.root = None
        self.comparisons = 0

    def insert(self, key, value):
        new_node = BSTNode(key, value)

        if self.root is None:
            self.root = new_node
            return

        current = self.root

        while True:

            if key < current.key:

                if current.left is None:
                    current.left = new_node
                    return

                current = current.left

            elif key > current.key:

                if current.right is None:
                    current.right = new_node
                    return

                current = current.right

            else:
                current.value = value
                return

    def search(self, key):

        current = self.root
        count = 0

        while current is not None:

            count += 1

            if key == current.key:
                self.comparisons += count
                return current.value

            elif key < current.key:
                current = current.left

            else:
                current = current.right

        self.comparisons += count
        return None

    # ------------------------------------------------------------
    # DELETE
    # ------------------------------------------------------------

    def delete(self, key):
        self.root = self._delete(self.root, key)

    def _delete(self, node, key):

        if node is None:
            return None

        if key < node.key:
            node.left = self._delete(node.left, key)

        elif key > node.key:
            node.right = self._delete(node.right, key)

        else:

            # Case 1: No child
            if node.left is None and node.right is None:
                return None

            # Case 2: One child
            if node.left is None:
                return node.right

            if node.right is None:
                return node.left

            # Case 3: Two children
            successor = self._minimum(node.right)

            node.key = successor.key
            node.value = successor.value

            node.right = self._delete(
                node.right,
                successor.key
            )

        return node

    def _minimum(self, node):

        current = node

        while current.left is not None:
            current = current.left

        return current

    # ------------------------------------------------------------
    # INORDER
    # ------------------------------------------------------------

    def inorder(self):

        result = []

        def traverse(node):

            if node is not None:
                traverse(node.left)
                result.append(node.key)
                traverse(node.right)

        traverse(self.root)

        return result

    # ------------------------------------------------------------
    # ITERATIVE HEIGHT
    # IMPORTANT: avoids RecursionError for N=10000
    # ------------------------------------------------------------

    def height(self):

        if self.root is None:
            return 0

        stack = [(self.root, 1)]
        maximum = 0

        while stack:

            node, level = stack.pop()

            if level > maximum:
                maximum = level

            if node.left is not None:
                stack.append(
                    (node.left, level + 1)
                )

            if node.right is not None:
                stack.append(
                    (node.right, level + 1)
                )

        return maximum

    # ------------------------------------------------------------
    # BST VALIDATION
    # ------------------------------------------------------------

    def is_bst(self):

        values = self.inorder()

        return values == sorted(values) and \
               len(values) == len(set(values))


